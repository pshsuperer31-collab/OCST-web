/* ── 검증 ────────────────────────────────────────────── */
const bad = [];
q.cards.forEach(c => {
  if (!q.sets[c.set]) bad.push(`${c.k}: 세트 ${c.set} 없음`);
  ['g','k','set','name','desc'].forEach(f => { if (!c[f]) bad.push(`${c.k}: ${f} 빔`); });
});
Object.keys(q.sets).forEach(k => {
  const s = q.sets[k];
  if (s.L.length !== 3 || s.U.length !== 3) bad.push(`${k}: 문항 ${s.L.length}+${s.U.length}`);
  if (s.lever.length !== 6) bad.push(`${k}: lever ${s.lever.length}`);
  s.L.concat(s.U).forEach((x, i) => {
    ['y','t','a','b','h'].forEach(f => { if (!x[f]) bad.push(`${k}/${i}: ${f} 빔`); });
  });
});
const keys = q.cards.map(c => c.k);
if (keys.length !== new Set(keys).size) bad.push('카드 키 중복');
if (bad.length) { console.error('✗', bad.join(' · ')); process.exit(1); }

fs.writeFileSync('qsets.json', JSON.stringify(q, null, 1));

